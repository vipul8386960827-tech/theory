// Top-Down
// I start with the overall problem and break it into smaller parts.
// Mostly used in system design and structuring code.

// Bottom-Up
// I build small components first and then combine them.
// Useful when the building blocks are clear.

// Brute Force
// I try all possible solutions first to get a baseline.
// Works well when constraints are small.

// Divide and Conquer
// I split the problem into independent subproblems and combine results.
// Common in searching and sorting problems.

// Greedy
// I make the best local choice at each step.
// Works when local decisions lead to a global optimum.

// Dynamic Programming
// I use it when subproblems repeat and recomputation can be avoided.
// I store results to optimize performance.

// Backtracking
// I explore all possible solutions but prune invalid ones early.
// Useful for combinations and constraint-based problems.

// Two Pointers
// I use two indices to traverse data efficiently.
// Common in sorted arrays and pair problems.

// Sliding Window
// I process a range of elements efficiently instead of recalculating.
// Useful for subarray and substring problems.